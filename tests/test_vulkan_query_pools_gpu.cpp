// The API-29 libvulkan stub exports Vulkan 1.1 only: load the 1.2/1.3 entry points from the device.
static PFN_vkResetQueryPool pfnResetQueryPool;
static PFN_vkCmdPipelineBarrier2 pfnCmdPipelineBarrier2;
static PFN_vkCmdBeginRendering pfnCmdBeginRendering;
static PFN_vkCmdEndRendering pfnCmdEndRendering;
#define vkResetQueryPool pfnResetQueryPool
#define vkCmdPipelineBarrier2 pfnCmdPipelineBarrier2
#define vkCmdBeginRendering pfnCmdBeginRendering
#define vkCmdEndRendering pfnCmdEndRendering

#define CHECK(x) do { VkResult r_ = (x); if (r_ != VK_SUCCESS) { printf("FAIL %s = %d (line %d)\n", #x, int(r_), __LINE__); exit(2); } } while (0)

static VkInstance instance;
static VkPhysicalDevice physical;
static VkDevice device;
static VkQueue queue;
static uint32_t family;
static VkPhysicalDeviceMemoryProperties memory;
static VkCommandPool commandPool;
static VkFormat depthFormat;
static uint32_t timestampBits;
static float timestampPeriod;

struct Target { VkImage color, depth; VkDeviceMemory colorMemory, depthMemory; VkImageView colorView, depthView; uint32_t width, height; };
struct Push { float rect[4]; float color[4]; float z; };

static uint32_t memoryType(uint32_t bits, VkMemoryPropertyFlags flags) {
  for (uint32_t i = 0; i < memory.memoryTypeCount; i++)
    if ((bits & (1u << i)) && (memory.memoryTypes[i].propertyFlags & flags) == flags) return i;
  printf("FAIL no memory type\n"); exit(2);
}

static void init() {
  VkApplicationInfo app{VK_STRUCTURE_TYPE_APPLICATION_INFO};
  app.pApplicationName = "ut3_query_pools"; app.apiVersion = VK_API_VERSION_1_3;
  VkInstanceCreateInfo ici{VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO}; ici.pApplicationInfo = &app;
  CHECK(vkCreateInstance(&ici, nullptr, &instance));
  uint32_t count = 1; VkResult r = vkEnumeratePhysicalDevices(instance, &count, &physical);
  if (r != VK_SUCCESS && r != VK_INCOMPLETE) { printf("FAIL no device\n"); exit(2); }
  VkPhysicalDeviceVulkan12Properties p12{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_2_PROPERTIES};
  VkPhysicalDeviceProperties2 props{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2, &p12};
  vkGetPhysicalDeviceProperties2(physical, &props);
  printf("device %s driver %s (%s) id %d api %u.%u.%u\n", props.properties.deviceName, p12.driverName, p12.driverInfo, int(p12.driverID),
         VK_API_VERSION_MAJOR(props.properties.apiVersion), VK_API_VERSION_MINOR(props.properties.apiVersion), VK_API_VERSION_PATCH(props.properties.apiVersion));
  timestampPeriod = props.properties.limits.timestampPeriod;
  vkGetPhysicalDeviceMemoryProperties(physical, &memory);
  uint32_t families = 0; vkGetPhysicalDeviceQueueFamilyProperties(physical, &families, nullptr);
  std::vector<VkQueueFamilyProperties> fp(families); vkGetPhysicalDeviceQueueFamilyProperties(physical, &families, fp.data());
  family = 0; while (family < families && !(fp[family].queueFlags & VK_QUEUE_GRAPHICS_BIT)) family++;
  timestampBits = fp[family].timestampValidBits;
  printf("queue family %u timestampValidBits %u period %.3f ns\n", family, timestampBits, timestampPeriod);
  float priority = 1;
  VkDeviceQueueCreateInfo qci{VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO}; qci.queueFamilyIndex = family; qci.queueCount = 1; qci.pQueuePriorities = &priority;
  VkPhysicalDeviceVulkan13Features f13{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_3_FEATURES}; f13.dynamicRendering = VK_TRUE;
  VkPhysicalDeviceVulkan12Features f12{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_2_FEATURES, &f13}; f12.hostQueryReset = VK_TRUE;
  VkPhysicalDeviceFeatures2 f{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2, &f12}; f.features.occlusionQueryPrecise = VK_TRUE;
  VkDeviceCreateInfo dci{VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO, &f}; dci.queueCreateInfoCount = 1; dci.pQueueCreateInfos = &qci;
  CHECK(vkCreateDevice(physical, &dci, nullptr, &device));
  vkGetDeviceQueue(device, family, 0, &queue);
  pfnResetQueryPool = (PFN_vkResetQueryPool)vkGetDeviceProcAddr(device, "vkResetQueryPool");
  pfnCmdPipelineBarrier2 = (PFN_vkCmdPipelineBarrier2)vkGetDeviceProcAddr(device, "vkCmdPipelineBarrier2");
  pfnCmdBeginRendering = (PFN_vkCmdBeginRendering)vkGetDeviceProcAddr(device, "vkCmdBeginRendering");
  pfnCmdEndRendering = (PFN_vkCmdEndRendering)vkGetDeviceProcAddr(device, "vkCmdEndRendering");
  if (!pfnResetQueryPool || !pfnCmdPipelineBarrier2 || !pfnCmdBeginRendering || !pfnCmdEndRendering) { puts("FAIL missing 1.3 entry points"); exit(2); }
  VkCommandPoolCreateInfo cpci{VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO}; cpci.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT; cpci.queueFamilyIndex = family;
  CHECK(vkCreateCommandPool(device, &cpci, nullptr, &commandPool));
  for (VkFormat format : {VK_FORMAT_D24_UNORM_S8_UINT, VK_FORMAT_D32_SFLOAT_S8_UINT, VK_FORMAT_D32_SFLOAT}) {
    VkFormatProperties fprops; vkGetPhysicalDeviceFormatProperties(physical, format, &fprops);
    if (fprops.optimalTilingFeatures & VK_FORMAT_FEATURE_DEPTH_STENCIL_ATTACHMENT_BIT) { depthFormat = format; break; }
  }
  printf("depth format %d\n", int(depthFormat));
}

static VkImageView makeImage(VkFormat format, VkImageUsageFlags usage, VkImageAspectFlags aspect, uint32_t w, uint32_t h, VkImage *image, VkDeviceMemory *mem) {
  VkImageCreateInfo ici{VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
  ici.imageType = VK_IMAGE_TYPE_2D; ici.format = format; ici.extent = {w, h, 1}; ici.mipLevels = 1; ici.arrayLayers = 1;
  ici.samples = VK_SAMPLE_COUNT_1_BIT; ici.tiling = VK_IMAGE_TILING_OPTIMAL; ici.usage = usage; ici.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
  CHECK(vkCreateImage(device, &ici, nullptr, image));
  VkMemoryRequirements req; vkGetImageMemoryRequirements(device, *image, &req);
  VkMemoryAllocateInfo mai{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO}; mai.allocationSize = req.size; mai.memoryTypeIndex = memoryType(req.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
  CHECK(vkAllocateMemory(device, &mai, nullptr, mem));
  CHECK(vkBindImageMemory(device, *image, *mem, 0));
  VkImageViewCreateInfo vci{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO}; vci.image = *image; vci.viewType = VK_IMAGE_VIEW_TYPE_2D; vci.format = format;
  vci.subresourceRange = {aspect, 0, 1, 0, 1};
  VkImageView view; CHECK(vkCreateImageView(device, &vci, nullptr, &view));
  return view;
}

static Target makeTarget(uint32_t w, uint32_t h, VkFormat colorFormat) {
  Target t{}; t.width = w; t.height = h;
  t.colorView = makeImage(colorFormat, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT, VK_IMAGE_ASPECT_COLOR_BIT, w, h, &t.color, &t.colorMemory);
  VkImageAspectFlags da = VK_IMAGE_ASPECT_DEPTH_BIT | (depthFormat == VK_FORMAT_D32_SFLOAT ? 0 : VK_IMAGE_ASPECT_STENCIL_BIT);
  t.depthView = makeImage(depthFormat, VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT, da, w, h, &t.depth, &t.depthMemory);
  return t;
}

static VkShaderModule module(const uint32_t *code, size_t bytes) {
  VkShaderModuleCreateInfo ci{VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO}; ci.codeSize = bytes; ci.pCode = code;
  VkShaderModule m; CHECK(vkCreateShaderModule(device, &ci, nullptr, &m)); return m;
}

static VkPipelineLayout layout;
static VkPipeline makePipeline(VkFormat colorFormat, bool colorWrite, bool depthWrite) {
  static VkShaderModule vs = module(probe_vert, sizeof probe_vert), fs = module(probe_frag, sizeof probe_frag);
  if (!layout) {
    VkPushConstantRange range{VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(Push)};
    VkPipelineLayoutCreateInfo lci{VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO}; lci.pushConstantRangeCount = 1; lci.pPushConstantRanges = &range;
    CHECK(vkCreatePipelineLayout(device, &lci, nullptr, &layout));
  }
  VkPipelineShaderStageCreateInfo stages[2]{{VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO}, {VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO}};
  stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT; stages[0].module = vs; stages[0].pName = "main";
  stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT; stages[1].module = fs; stages[1].pName = "main";
  VkPipelineVertexInputStateCreateInfo vi{VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO};
  VkPipelineInputAssemblyStateCreateInfo ia{VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO}; ia.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;
  VkPipelineViewportStateCreateInfo vp{VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO}; vp.viewportCount = 1; vp.scissorCount = 1;
  VkPipelineRasterizationStateCreateInfo rs{VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO}; rs.cullMode = VK_CULL_MODE_NONE; rs.lineWidth = 1;
  VkPipelineMultisampleStateCreateInfo ms{VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO}; ms.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;
  VkPipelineDepthStencilStateCreateInfo ds{VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO};
  ds.depthTestEnable = VK_TRUE; ds.depthWriteEnable = depthWrite; ds.depthCompareOp = VK_COMPARE_OP_LESS_OR_EQUAL;
  VkPipelineColorBlendAttachmentState att{}; att.colorWriteMask = colorWrite ? 0xf : 0;
  VkPipelineColorBlendStateCreateInfo cb{VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO}; cb.attachmentCount = 1; cb.pAttachments = &att;
  VkDynamicState dyn[2] = {VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR};
  VkPipelineDynamicStateCreateInfo dy{VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO}; dy.dynamicStateCount = 2; dy.pDynamicStates = dyn;
  VkPipelineRenderingCreateInfo rci{VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO}; rci.colorAttachmentCount = 1; rci.pColorAttachmentFormats = &colorFormat;
  rci.depthAttachmentFormat = depthFormat; rci.stencilAttachmentFormat = depthFormat == VK_FORMAT_D32_SFLOAT ? VK_FORMAT_UNDEFINED : depthFormat;
  VkGraphicsPipelineCreateInfo pci{VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO, &rci};
  pci.stageCount = 2; pci.pStages = stages; pci.pVertexInputState = &vi; pci.pInputAssemblyState = &ia; pci.pViewportState = &vp; pci.pRasterizationState = &rs;
  pci.pMultisampleState = &ms; pci.pDepthStencilState = &ds; pci.pColorBlendState = &cb; pci.pDynamicState = &dy; pci.layout = layout;
  VkPipeline p; CHECK(vkCreateGraphicsPipelines(device, VK_NULL_HANDLE, 1, &pci, nullptr, &p)); return p;
}

static void barrier(VkCommandBuffer cmd, const Target &t, bool first) {
  VkImageMemoryBarrier2 b[2]{{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER_2}, {VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER_2}};
  b[0].srcStageMask = VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT; b[0].srcAccessMask = first ? 0 : VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT;
  b[0].dstStageMask = VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT; b[0].dstAccessMask = VK_ACCESS_2_COLOR_ATTACHMENT_READ_BIT | VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT;
  b[0].oldLayout = first ? VK_IMAGE_LAYOUT_UNDEFINED : VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL; b[0].newLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
  b[0].srcQueueFamilyIndex = b[0].dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED; b[0].image = t.color; b[0].subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
  b[1] = b[0];
  b[1].srcStageMask = b[1].dstStageMask = VK_PIPELINE_STAGE_2_EARLY_FRAGMENT_TESTS_BIT | VK_PIPELINE_STAGE_2_LATE_FRAGMENT_TESTS_BIT;
  b[1].srcAccessMask = first ? 0 : VK_ACCESS_2_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;
  b[1].dstAccessMask = VK_ACCESS_2_DEPTH_STENCIL_ATTACHMENT_READ_BIT | VK_ACCESS_2_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;
  b[1].oldLayout = first ? VK_IMAGE_LAYOUT_UNDEFINED : VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL; b[1].newLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;
  b[1].image = t.depth; b[1].subresourceRange = {VkImageAspectFlags(VK_IMAGE_ASPECT_DEPTH_BIT | (depthFormat == VK_FORMAT_D32_SFLOAT ? 0 : VK_IMAGE_ASPECT_STENCIL_BIT)), 0, 1, 0, 1};
  VkDependencyInfo dep{VK_STRUCTURE_TYPE_DEPENDENCY_INFO}; dep.imageMemoryBarrierCount = 2; dep.pImageMemoryBarriers = b;
  vkCmdPipelineBarrier2(cmd, &dep);
}

static void beginRendering(VkCommandBuffer cmd, const Target &t, bool clear, float depth) {
  VkRenderingAttachmentInfo color{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
  color.imageView = t.colorView; color.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
  color.loadOp = clear ? VK_ATTACHMENT_LOAD_OP_CLEAR : VK_ATTACHMENT_LOAD_OP_LOAD; color.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
  VkRenderingAttachmentInfo ds = color; ds.imageView = t.depthView; ds.imageLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;
  ds.clearValue.depthStencil = {depth, 0};
  VkRenderingInfo ri{VK_STRUCTURE_TYPE_RENDERING_INFO}; ri.renderArea = {{0, 0}, {t.width, t.height}}; ri.layerCount = 1;
  ri.colorAttachmentCount = 1; ri.pColorAttachments = &color; ri.pDepthAttachment = &ds;
  ri.pStencilAttachment = depthFormat == VK_FORMAT_D32_SFLOAT ? nullptr : &ds;
  vkCmdBeginRendering(cmd, &ri);
  VkViewport v{0, 0, float(t.width), float(t.height), 0, 1}; VkRect2D s{{0, 0}, {t.width, t.height}};
  vkCmdSetViewport(cmd, 0, 1, &v); vkCmdSetScissor(cmd, 0, 1, &s);
}

static VkQueryPool makePool(uint32_t size) {
  VkQueryPoolCreateInfo ci{VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO}; ci.queryType = VK_QUERY_TYPE_OCCLUSION; ci.queryCount = size;
  VkQueryPool p; CHECK(vkCreateQueryPool(device, &ci, nullptr, &p)); vkResetQueryPool(device, p, 0, size); return p;
}

static void submit(VkCommandBuffer cmd) {
  VkFenceCreateInfo fci{VK_STRUCTURE_TYPE_FENCE_CREATE_INFO}; VkFence fence; CHECK(vkCreateFence(device, &fci, nullptr, &fence));
  VkSubmitInfo si{VK_STRUCTURE_TYPE_SUBMIT_INFO}; si.commandBufferCount = 1; si.pCommandBuffers = &cmd;
  CHECK(vkQueueSubmit(queue, 1, &si, fence)); CHECK(vkWaitForFences(device, 1, &fence, VK_TRUE, 5000000000ull));
  vkDestroyFence(device, fence, nullptr);
}

static VkCommandBuffer newCommandBuffer() {
  VkCommandBufferAllocateInfo ai{VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO}; ai.commandPool = commandPool; ai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY; ai.commandBufferCount = 1;
  VkCommandBuffer cmd; CHECK(vkAllocateCommandBuffers(device, &ai, &cmd)); return cmd;
}

static void draw(VkCommandBuffer cmd, float x0, float y0, float x1, float y1, float z) {
  Push p{{x0, y0, x1, y1}, {0.9f, 0.6f, 0.3f, 1.0f}, z};
  vkCmdPushConstants(cmd, layout, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof p, &p);
  vkCmdDraw(cmd, 3, 1, 0, 0);
}

// One render pass: an occluder at depth 0.25 over the left half, then for every index a visible query
// (right half, z 0.5) and a hidden one (left half behind the occluder, z 0.75). Results are read with WAIT.
static int correctness() {
  Target t = makeTarget(256, 256, VK_FORMAT_R8G8B8A8_UNORM);
  VkPipeline writePipe = makePipeline(VK_FORMAT_R8G8B8A8_UNORM, true, true), queryPipe = makePipeline(VK_FORMAT_R8G8B8A8_UNORM, false, false);
  const uint32_t sizes[] = {64, 128, 256, 512, 1024, 2048, 4096, 8192, 16384};
  int failures = 0;
  for (uint32_t size : sizes) {
    std::vector<uint32_t> indices;
    for (uint32_t i : {0u, 1u, 63u, 64u, 127u, 255u, 511u, 1022u, 1023u, 1024u, 2047u, 4095u, 8191u, 16383u})
      if (i < size && std::find(indices.begin(), indices.end(), i) == indices.end()) indices.push_back(i);
    if (std::find(indices.begin(), indices.end(), size - 1) == indices.end()) indices.push_back(size - 1);
    VkQueryPool pool = makePool(size);
    // Each probed index pair: visible at k, hidden at the paired index (k ^ 1, or k-1).
    VkCommandBuffer cmd = newCommandBuffer();
    VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO}; CHECK(vkBeginCommandBuffer(cmd, &bi));
    barrier(cmd, t, true);
    beginRendering(cmd, t, true, 1.0f);
    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, writePipe);
    draw(cmd, -1, -1, 0, 3, 0.25f);      // occluder over the left part: triangle (-1,-1) (0,-1) (-1,3)
    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, queryPipe);
    std::vector<std::pair<uint32_t, bool>> probes;
    for (uint32_t k : indices) {
      bool hidden = false;
      uint32_t other = (k & 1) ? k - 1 : k + 1;
      if (other >= size || std::find(indices.begin(), indices.end(), other) != indices.end()) other = UINT32_MAX;
      vkCmdBeginQuery(cmd, pool, k, VK_QUERY_CONTROL_PRECISE_BIT);
      draw(cmd, 0.2f, -0.9f, 0.9f, 0.9f, 0.5f);           // right half: visible
      vkCmdEndQuery(cmd, pool, k);
      probes.push_back({k, hidden});
      if (other != UINT32_MAX) {
        vkCmdBeginQuery(cmd, pool, other, VK_QUERY_CONTROL_PRECISE_BIT);
        draw(cmd, -0.95f, -0.9f, -0.6f, 0.9f, 0.75f);      // left half behind the occluder: hidden
        vkCmdEndQuery(cmd, pool, other);
        probes.push_back({other, true});
      }
    }
    vkCmdEndRendering(cmd);
    CHECK(vkEndCommandBuffer(cmd));
    submit(cmd);
    std::string line;
    int bad = 0;
    for (auto [k, hidden] : probes) {
      uint64_t samples = 0xdeadbeef;
      VkResult r = vkGetQueryPoolResults(device, pool, k, 1, sizeof samples, &samples, sizeof samples, VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT);
      bool ok = r == VK_SUCCESS && (hidden ? samples == 0 : samples > 0);
      if (!ok) bad++;
      char text[64]; snprintf(text, sizeof text, " %u%s=%llu%s", k, hidden ? "h" : "v", (unsigned long long)samples, ok ? "" : "!");
      line += text;
    }
    printf("%s pool %5u:%s\n", bad ? "FAIL" : "PASS", size, line.c_str());
    failures += bad;
    vkFreeCommandBuffers(device, commandPool, 1, &cmd);
    vkDestroyQueryPool(device, pool, nullptr);
  }
  return failures;
}

// Every index of a pool in one render pass (even visible, odd hidden), over several frames with host resets,
// as DXVK uses a pool: shows whether a large pool keeps real counts when all of its slots are in flight.
static int fullPools() {
  Target t = makeTarget(256, 256, VK_FORMAT_R8G8B8A8_UNORM);
  VkPipeline writePipe = makePipeline(VK_FORMAT_R8G8B8A8_UNORM, true, true), queryPipe = makePipeline(VK_FORMAT_R8G8B8A8_UNORM, false, false);
  int failures = 0;
  for (uint32_t size : {1024u, 2048u, 4096u, 8192u}) {
    VkQueryPool pool = makePool(size);
    for (int frame = 0; frame < 3; frame++) {
      vkResetQueryPool(device, pool, 0, size);
      VkCommandBuffer cmd = newCommandBuffer();
      VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO}; CHECK(vkBeginCommandBuffer(cmd, &bi));
      barrier(cmd, t, frame == 0 && size == 1024);
      beginRendering(cmd, t, true, 1.0f);
      vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, writePipe);
      draw(cmd, -1, -1, 0, 3, 0.25f);
      vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, queryPipe);
      // Descending order like DXVK's free list (it pops the highest index first).
      for (uint32_t i = size; i-- > 0;) {
        bool hidden = i & 1;
        vkCmdBeginQuery(cmd, pool, i, VK_QUERY_CONTROL_PRECISE_BIT);
        if (hidden) draw(cmd, -0.95f, -0.9f, -0.6f, 0.9f, 0.75f); else draw(cmd, 0.2f, -0.9f, 0.9f, 0.9f, 0.5f);
        vkCmdEndQuery(cmd, pool, i);
      }
      vkCmdEndRendering(cmd);
      CHECK(vkEndCommandBuffer(cmd));
      submit(cmd);
      std::vector<uint64_t> results(size);
      VkResult r = vkGetQueryPoolResults(device, pool, 0, size, size * 8, results.data(), 8, VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT);
      unsigned wrong = 0, firstWrong = UINT32_MAX; uint64_t visible = 0;
      for (uint32_t i = 0; i < size; i++) {
        bool ok = (i & 1) ? results[i] == 0 : results[i] > 0;
        if (!(i & 1) && !visible) visible = results[i];
        if (!ok) { wrong++; if (firstWrong == UINT32_MAX) firstWrong = i; }
      }
      printf("%s full pool %5u frame %d: result %d, %u wrong (first %d), visible samples %llu\n", wrong || r ? "FAIL" : "PASS", size, frame, int(r), wrong,
             firstWrong == UINT32_MAX ? -1 : int(firstWrong), (unsigned long long)visible);
      failures += wrong + (r != VK_SUCCESS);
      vkFreeCommandBuffers(device, commandPool, 1, &cmd);
    }
    vkDestroyQueryPool(device, pool, nullptr);
  }
  return failures;
}

// GPU cost per frame: one render pass (LOAD/STORE) at the game's size, 'draws' small draws each inside an occlusion
// query, with different pool assignment patterns. Wall time of submit+wait (GPU bound) and timestamps if available.
static void perf(int draws, int frames, uint32_t width, uint32_t height) {
  Target t = makeTarget(width, height, VK_FORMAT_R16G16B16A16_SFLOAT);
  VkPipeline pipe = makePipeline(VK_FORMAT_R16G16B16A16_SFLOAT, true, true);
  VkQueryPool ts = VK_NULL_HANDLE;
  if (timestampBits) {
    VkQueryPoolCreateInfo ci{VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO}; ci.queryType = VK_QUERY_TYPE_TIMESTAMP; ci.queryCount = 2;
    CHECK(vkCreateQueryPool(device, &ci, nullptr, &ts));
  }
  const int poolCount = (draws + 63) / 64 + 1;
  std::vector<VkQueryPool> small(poolCount);
  for (auto &p : small) p = makePool(64);
  VkQueryPool big = makePool(1024), huge = makePool(4096);
  std::mt19937 rng(1234);
  struct Mode { const char *name; int kind; };
  const Mode modes[] = {{"no queries", 0}, {"one 1024 pool", 1}, {"64-pools in order", 2}, {"64-pools alternating", 3}, {"64-pools shuffled", 4},
                        {"no queries", 0}, {"one 1024 pool", 1}, {"64-pools shuffled", 4},
                        {"4096 pool descending", 5}, {"4096 pool scattered", 6}, {"1024 pool not precise", 7}, {"no queries", 0}};
  VkCommandBuffer cmd = newCommandBuffer();
  {
    VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO}; CHECK(vkBeginCommandBuffer(cmd, &bi));
    barrier(cmd, t, true); beginRendering(cmd, t, true, 1.0f); vkCmdEndRendering(cmd);
    CHECK(vkEndCommandBuffer(cmd)); submit(cmd);
  }
  bool first = false;
  for (const Mode &mode : modes) {
    std::vector<double> wall, gpu;
    for (int f = 0; f < frames; f++) {
      std::vector<std::pair<VkQueryPool, uint32_t>> slots(draws);
      std::vector<uint32_t> next(poolCount, 0);
      for (int i = 0; i < draws; i++) {
        int p = mode.kind == 2 ? i / 64 : mode.kind == 3 ? i % poolCount : mode.kind == 4 ? int(rng() % poolCount) : 0;
        if (mode.kind >= 2 && mode.kind <= 4) { while (next[p] >= 64) p = (p + 1) % poolCount; slots[i] = {small[p], next[p]++}; }
        else if (mode.kind == 5) slots[i] = {huge, uint32_t(4095 - i)};
        else slots[i] = {big, uint32_t(i)};
      }
      if (mode.kind == 6) {   // distinct random slots of the 4096 pool, as a LIFO list recycles them
        std::vector<uint32_t> ids(4096);
        for (uint32_t k = 0; k < 4096; k++) ids[k] = k;
        std::shuffle(ids.begin(), ids.end(), rng);
        for (int i = 0; i < draws; i++) slots[i] = {huge, ids[i]};
      }
      if (mode.kind) {
        if (mode.kind == 1 || mode.kind == 7) vkResetQueryPool(device, big, 0, draws);
        else if (mode.kind == 5 || mode.kind == 6) vkResetQueryPool(device, huge, 0, 4096);
        else for (auto p : small) vkResetQueryPool(device, p, 0, 64);
      }
      CHECK(vkResetCommandBuffer(cmd, 0));
      VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO}; bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
      CHECK(vkBeginCommandBuffer(cmd, &bi));
      if (ts) { vkCmdResetQueryPool(cmd, ts, 0, 2); vkCmdWriteTimestamp(cmd, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, ts, 0); }
      barrier(cmd, t, first); first = false;
      beginRendering(cmd, t, false, 1.0f);
      vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, pipe);
      for (int i = 0; i < draws; i++) {
        float x = -1.0f + 1.8f * float(i % 16) / 16.0f, y = -1.0f + 1.8f * float((i / 16) % 16) / 16.0f;
        if (mode.kind) vkCmdBeginQuery(cmd, slots[i].first, slots[i].second, mode.kind == 7 ? 0 : VK_QUERY_CONTROL_PRECISE_BIT);
        draw(cmd, x, y, x + 0.3f, y + 0.3f, 0.5f);
        if (mode.kind) vkCmdEndQuery(cmd, slots[i].first, slots[i].second);
      }
      vkCmdEndRendering(cmd);
      if (ts) vkCmdWriteTimestamp(cmd, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, ts, 1);
      CHECK(vkEndCommandBuffer(cmd));
      auto start = std::chrono::steady_clock::now();
      submit(cmd);
      wall.push_back(std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - start).count());
      if (ts) {
        uint64_t stamps[2]{};
        if (vkGetQueryPoolResults(device, ts, 0, 2, sizeof stamps, stamps, sizeof(uint64_t), VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT) == VK_SUCCESS)
          gpu.push_back(double(stamps[1] - stamps[0]) * timestampPeriod * 1e-6);
      }
      if (mode.kind) {   // every query drew a visible quad: all must be positive
        unsigned zero = 0;
        for (auto [p, k] : slots) { uint64_t s = 0; vkGetQueryPoolResults(device, p, k, 1, 8, &s, 8, VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT); zero += s == 0; }
        if (zero && f == frames - 1) printf("   note: %u of %d visible queries returned 0\n", zero, draws);
      }
    }
    auto median = [](std::vector<double> v) { if (v.empty()) return 0.0; std::sort(v.begin(), v.end()); return v[v.size() / 2]; };
    int switches = 0;
    printf("%-22s draws %d: wall median %.2f ms, gpu median %.2f ms (frames %d)\n", mode.name, draws, median(wall), median(gpu), frames);
    (void)switches;
  }
}

int main(int argc, char **argv) {
  setvbuf(stdout, nullptr, _IONBF, 0);
  init();
  std::string what = argc > 1 ? argv[1] : "correct";
  if (what == "correct") { int f = correctness(); printf("%s correctness failures=%d\n", f ? "FAIL" : "PASS", f); return f ? 1 : 0; }
  if (what == "full") { int f = fullPools(); printf("%s full-pool failures=%d\n", f ? "FAIL" : "PASS", f); return f ? 1 : 0; }
  if (what == "perf") { perf(argc > 2 ? atoi(argv[2]) : 256, argc > 3 ? atoi(argv[3]) : 20, argc > 4 ? atoi(argv[4]) : 2424, argc > 5 ? atoi(argv[5]) : 1080); return 0; }
  printf("usage: test_vulkan_query_pools_gpu correct | full | perf [draws] [frames] [width] [height]\n");
  return 2;
}

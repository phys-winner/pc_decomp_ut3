// Raw Vulkan oracle for occlusion queries on the system driver (no DXVK, no window); tests/test_vulkan_query_pools_gpu.py
// builds and runs it on UT3_TEST_ANDROID.
//   correct : which pool sizes / query indices return real sample counts (visible > 0, depth-hidden 0)
//   full    : every slot of 1024..8192-entry pools in one render, three frames with host resets
//   perf [draws] [frames] [width] [height] : GPU time of one 2424x1080 RGBA16F + D24S8 render with a query per draw,
//             all from one pool or spread over 64-entry pools (PowerVR ends the render at every pool change)
